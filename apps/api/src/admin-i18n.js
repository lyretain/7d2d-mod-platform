  function currentLang() {
    const saved = root.localStorage && root.localStorage.getItem('modPlatformLang');
    if (saved === 'zh' || saved === 'en') return saved;
    return String((root.navigator && root.navigator.language) || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  function t(key, vars) {
    const lang = currentLang();
    const dict = lang === 'en' ? en : zh;
    let text = dict[key] || zh[key] || key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.split('{' + name + '}').join(String(value));
    }
    return text;
  }

  root.I18N = { zh, en, t, currentLang };
